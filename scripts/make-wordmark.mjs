// Traces the "CoreMama" wordmark into SVG path data so the logo can be stroke-animated.
// Usage: node scripts/make-wordmark.mjs <path-to-font.ttf> [weight]
// Output: src/components/brand/wordmark-paths.ts
import fs from "node:fs";
import path from "node:path";
import * as fontkit from "fontkit";

const [, , fontPath, weightArg] = process.argv;
if (!fontPath) {
  console.error("usage: node scripts/make-wordmark.mjs <font.ttf> [weight]");
  process.exit(1);
}
let font = fontkit.openSync(fontPath);
const weight = Number(weightArg ?? 500);
if (font.variationAxes && font.variationAxes.wght) {
  font = font.getVariation({ wght: weight });
}
const UNITS = 1000;
const scale = UNITS / font.unitsPerEm;
const text = "CoreMama";
const run = font.layout(text);

let x = 0;
const glyphs = [];
run.glyphs.forEach((glyph, i) => {
  const pos = run.positions[i];
  const d = glyph.path
    .scale(scale, -scale) // flip Y for SVG
    .translate(x + pos.xOffset * scale, 0)
    .toSVG();
  glyphs.push({ char: text[i] ?? "", d });
  x += pos.xAdvance * scale;
});

const ascent = font.ascent * scale;
const descent = font.descent * scale;
const width = Math.round(x);
const out = `// AUTO-GENERATED by scripts/make-wordmark.mjs — do not edit by hand.
// Source font: ${path.basename(fontPath)} (wght ${weight}); units per em normalised to ${UNITS}.
export const WORDMARK = {
  width: ${width},
  ascent: ${Math.round(ascent)},
  descent: ${Math.round(descent)},
  glyphs: ${JSON.stringify(glyphs, null, 2)},
} as const;
`;
fs.writeFileSync("src/components/brand/wordmark-paths.ts", out);
console.log(`wrote ${glyphs.length} glyphs, width ${width}, ascent ${Math.round(ascent)}, descent ${Math.round(descent)}`);
